-- Убирает провалившиеся операции добавления в белый список, чтобы их можно было поставить заново.
--
-- ЗАЧЕМ. Ключ идемпотентности у AllowlistAdd строится по СЕТИ И АДРЕСУ
-- (allowlist-add:bsc-testnet:0x…), а не по заявке — так и задумано: один и тот же кошелёк не
-- нужно вносить в список дважды. Но у ключа нет срока и нет оглядки на исход: операция, упавшая
-- при постановке, занимает ключ навсегда. Новая заявка того же инвестора ставит только
-- TokenAllocation, добавление в список молча пропускается, а минт на адрес вне белого списка
-- контракт отвергнет.
--
-- Именно это и произошло: попытка от 10:56 упала (подпись шла ключом, не назначенным агентом),
-- заявка от 11:55 добавление в список уже не поставила, и по сети isAllowed() у адреса — ложь.
--
-- ЧТО ДЕЛАЕТ. Удаляет строки AllowlistAdd (Type = 0) в статусе Failed (Status = 3), у которых
-- НЕТ ссылки на транзакцию. Отсутствие ссылки — это доказательство, что в сеть ничего не ушло:
-- операция не дожила до отправки. Такую строку можно убрать, ничего не потеряв.
--
-- ЧЕГО НЕ ДЕЛАЕТ. Не трогает операции с TransactionRef, даже провалившиеся: транзакция, которая
-- была отправлена и отвергнута сетью, — это факт, который должен остаться в истории.
-- Не трогает TokenAllocation: там ключ привязан к событию активации, и повторная заявка ставит
-- операцию заново без посторонней помощи.
--
-- ПОСЛЕ ЗАПУСКА. Заявку нужно аннулировать и подать заново: событие активации по ней уже
-- отгремело, задним числом операции никто не поставит.
--
--   psql "$CONNECTION_STRING" -f scripts/clear-failed-allowlist-operations.sql
--
-- Транзакция: либо всё, либо ничего.

BEGIN;

-- 0. Что будет удалено (только чтение).
SELECT "Id", "IdempotencyKey", "CreatedAtUtc", left(coalesce("Error", '—'), 80) AS "ошибка"
FROM blockchain_operations
WHERE "Type" = 0                                         -- AllowlistAdd
  AND "Status" = 3                                       -- Failed
  AND ("TransactionRef" IS NULL OR "TransactionRef" = '');

-- 1. Удаление. Условие по TransactionRef оставлено намеренно: строка, успевшая отправить
--    транзакцию, остаётся в истории, чем бы та ни закончилась.
DELETE FROM blockchain_operations
WHERE "Type" = 0
  AND "Status" = 3
  AND ("TransactionRef" IS NULL OR "TransactionRef" = '');

-- 2. Контроль: занятых ключей добавления в список остаться не должно.
SELECT 'осталось незавершённых AllowlistAdd: ' || count(*)::text AS check
FROM blockchain_operations
WHERE "Type" = 0
  AND "Status" = 3
  AND ("TransactionRef" IS NULL OR "TransactionRef" = '');

COMMIT;
